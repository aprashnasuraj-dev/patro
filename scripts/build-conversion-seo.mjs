import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { loadCalendarSnapshot } from "./calendar-snapshot.mjs";
import { INDEXED_CALENDAR_YEARS, SITE } from "./seo-config.mjs";
import { urlsetXml, updateSitemapIndex } from "./sitemap-utils.mjs";
const months=["baisakh","jestha","ashadh","shrawan","bhadra","ashwin","kartik","mangsir","poush","magh","falgun","chaitra"];
const allowed=new Set(INDEXED_CALENDAR_YEARS);
const rows=(await loadCalendarSnapshot()).filter(row=>allowed.has(Number(row.bs?.year))&&Number(row.bs.year)>=1970&&Number(row.bs.year)<=2093);
const routes=rows.flatMap(row=>[`/bs-to-ad/${row.bs.year}-${months[row.bs.month-1]}-${row.bs.day}`,`/ad-to-bs/${row.ad}`]);
if(new Set(routes).size!==routes.length)throw new Error("Duplicate conversion routes");
const root=process.cwd(),file="sitemap-conversions.xml";
await writeFile(resolve(root,"public",file),urlsetXml(routes));
await updateSitemapIndex(resolve(root,"public/sitemap.xml"),[{file}]);
const path=resolve(root,"public/seo-manifest.json"),manifest=JSON.parse(await readFile(path,"utf8"));
manifest.sitemap_files=[...new Set([...(manifest.sitemap_files||[]),file])];
manifest.indexed_conversion_route_count=routes.length;
manifest.conversion_examples=[`${SITE}/bs-to-ad/2083-baisakh-1`,`${SITE}/ad-to-bs/2026-04-14`];
await writeFile(path,JSON.stringify(manifest,null,2)+"\n");
console.log(`Conversion SEO: ${routes.length} canonical intent pages from ${rows.length} validated calendar dates; rendered at the edge, without thousands of HTML files.`);
