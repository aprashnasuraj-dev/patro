export function habitLocaleFromUrl(url: URL): HabitLocale {
  return url.searchParams.get("lang") === "en" ? "en" : "ne";
}
export function habitCatalogue(locale: HabitLocale): Record<string,string> {
  return HABIT_CATALOGUES[locale];
}
export function habitT(locale: HabitLocale, key: string, vars: Record<string,string|number> = {}): string {
  const catalog = HABIT_CATALOGUES[locale];
  const template = catalog[key] ?? HABIT_CATALOGUES.ne[key] ?? key;
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (_, k) => String(vars[k] ?? ""));
}
