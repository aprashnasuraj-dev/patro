/**
 * Explore engine contract.
 *  1. Isolation: the engine claims none of the existing published URLs, sitemap files, growth prefixes,
 *     redirects or private routes — it returns null for them, so production behaves exactly as before.
 *  2. Behaviour: pages render from prebuilt R2 records (built here by the real builder), with canonical,
 *     robots, ETag/304, HEAD, 301 normalisation, 404 for missing pages and 503 when storage is absent.
 */
import { execFileSync } from "node:child_process";
import { existsSync, mkdtempSync, readFileSync, readdirSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { exploreResponse, isExplorePath } from "../worker/explore";
import { EXPLORE_CONFIG, EXPLORE_FAMILIES, pageKey, sitemapKey } from "../worker/explore/families";
import { exploreRedirect, ROOT_DISTRICT_ALIASES } from "../worker/explore/redirects";
import geo from "../worker/explore/nepal-geo.json";

const SITE = "https://aafnaipatro.com";
const req = (path: string, init?: RequestInit) => new Request(SITE + path, init);

let out = "";
const bucket = {
  async get(key: string) {
    const prefix = EXPLORE_CONFIG.storage_prefix + "/";
    if (!key.startsWith(prefix)) return null;
    const file = join(out, key.slice(prefix.length));
    if (!existsSync(file)) return null;
    const text = readFileSync(file, "utf8");
    return { body: new Response(text).body!, httpEtag: '"t"', text: async () => text };
  },
};
const env = { ARCHIVE: bucket, PUBLIC_SITE_URL: SITE };

beforeAll(() => {
  out = mkdtempSync(join(tmpdir(), "explore-"));
  execFileSync(process.execPath, ["--max-old-space-size=6144", "scripts/explore/build.mjs", "--out", out], { stdio: "pipe" });
}, 300_000);
afterAll(() => rmSync(out, { recursive: true, force: true }));

describe("isolation from existing routes", () => {
  it("claims none of the published baseline URLs", () => {
    const baseline = JSON.parse(readFileSync("seo/published-url-baseline.json", "utf8")) as { paths: string[] };
    expect(baseline.paths.length).toBeGreaterThan(22_000);
    const claimed = baseline.paths.filter((p) => isExplorePath(p));
    expect(claimed).toEqual([]);
  });

  it("claims none of the existing sitemap files", () => {
    const index = readFileSync("public/sitemap.xml", "utf8");
    const files = [...index.matchAll(/<loc>[^<]*\/(sitemap[^<]*\.xml)<\/loc>/g)].map((m) => "/" + m[1]);
    const local = readdirSync("public").filter((f) => /^sitemap.*\.xml$/.test(f)).map((f) => "/" + f);
    expect(files.length).toBeGreaterThan(10);
    for (const f of [...files, ...local, "/sitemap.xml", "/robots.txt", "/sitemap-growth.xml"]) expect(isExplorePath(f), f).toBe(false);
  });

  it("claims none of the known route prefixes, redirects or private surfaces", async () => {
    const existing = [
      "/", "/today", "/date/2026-10-09", "/calendar/2083/06", "/bs-to-ad/2083-ashwin-23", "/ad-to-bs/2026-10-09", "/convert", "/tools", "/tools/age",
      "/festivals", "/festivals/dashain", "/time-machine", "/on-this-day", "/onthisday/10-09", "/samudaya", "/nepal-sambat/mandala", "/rashifal", "/janmapatro",
      "/moon", "/moon/full-moon/2026", "/eclipse", "/nepal", "/nepal/time", "/nepal/year", "/nepal/trek-weather", "/nepal/trek-weather/lukla", "/nepal/time/", "/us/festivals", "/weather", "/de/mond", "/guides", "/fm", "/tv", "/samachar",
      "/api/v1/today", "/compat-api/x", "/me", "/admin", "/auth/google", "/data/calendar/x.json", "/assets/app.js", "/aap/runtime.js", "/embed/x", "/x/y",
      "/jyotish/rashifal", "/astro", "/tithi", "/card", "/explore", "/search", "/places", "/placement", "/place-birthday", "/sitemap-x.xml", "/sitemap-places.xml",
    ];
    for (const path of existing) {
      expect(isExplorePath(path), path).toBe(false);
      expect(await exploreResponse(req(path), env), path).toBeNull();
    }
  });

  it("never redirects or claims a path the site already serves at the root", () => {
    const baseline = new Set((JSON.parse(readFileSync("seo/published-url-baseline.json", "utf8")) as { paths: string[] }).paths.map((p) => p.replace(/\/+$/, "") || "/"));
    // sitemap-growth.xml is generated by npm run build; a fresh checkout (the explore deploy job) uses the known growth paths.
    const growthFile = ["public/sitemap-growth.xml", "dist/sitemap-growth.xml"].find((f) => existsSync(f));
    const growth = growthFile
      ? [...readFileSync(growthFile, "utf8").matchAll(/<loc>https?:\/\/[^/]+(\/[^<]*)<\/loc>/g)].map((m) => m[1])
      : ["/nepal", "/nepal/time", "/nepal/year", "/nepal/trek-weather", "/nepal/trek-weather/lukla", "/nepal/trek-weather/everest-base-camp", "/moon", "/eclipse", "/weather"];
    const topLevel = new Set([...(existsSync("dist") ? readdirSync("dist") : []), ...readdirSync("public")].map((f) => f.replace(/\.[a-z0-9]+$/i, "").toLowerCase()));
    expect(ROOT_DISTRICT_ALIASES.length).toBeGreaterThan(77);
    for (const alias of ROOT_DISTRICT_ALIASES) {
      expect(baseline.has("/" + alias), alias).toBe(false);
      expect(growth.includes("/" + alias), alias).toBe(false);
      expect(topLevel.has(alias), alias).toBe(false);
    }
    // Every growth page under /nepal stays with the growth handler.
    for (const path of growth.filter((p) => p.startsWith("/nepal"))) {
      expect(isExplorePath(path), path).toBe(false);
      expect(exploreRedirect(path), path).toBeNull();
    }
  });

  it("claims exactly the province and district slugs below /nepal", () => {
    const nepal = EXPLORE_FAMILIES.find((f) => f.id === "nepal")!;
    expect(nepal.serve_root).toBe(false);
    expect(new Set(nepal.segments)).toEqual(new Set([...geo.provinces.map((p) => p.slug), ...geo.districts.map((d) => d.slug)]));
    expect(nepal.segments!.length).toBe(84);
  });

  it("uses prefixes that never overlap each other", () => {
    for (const a of EXPLORE_FAMILIES) for (const b of EXPLORE_FAMILIES) if (a !== b) expect(a.prefix.startsWith(b.prefix + "/") || a.prefix === b.prefix).toBe(false);
  });

  it("is wired before other handlers only through a null-returning hook", () => {
    const entry = readFileSync("worker/optimized-entry.ts", "utf8");
    expect(entry).toMatch(/const explore = await exploreResponse\(request, env as any, ctx\);\s*if \(explore\) return explore;/);
  });
});

describe("page rendering from R2 records", () => {
  it("builds every Nepal page type and holds back thin pages", () => {
    const manifest = JSON.parse(readFileSync(join(out, "manifest.json"), "utf8"));
    expect(manifest.families.nepal.pages).toBeGreaterThan(15_000);
    expect(manifest.families.nepal.indexable / manifest.families.nepal.pages).toBeGreaterThan(0.9);
    for (const page of ["nepal/bajhang", "nepal/sudurpashchim-province", "nepal/bajhang/jayaprithvi", "nepal/bajhang/jayaprithvi/ward-11", "nepal/bajhang/vdc", "nepal/bajhang/vdc/chainpur", "nepal/dolakha", "nepal/ramechhap", "nepal/kathmandu/kathmandu/ward-32"]) {
      expect(existsSync(join(out, "pages", page + ".json")), page).toBe(true);
    }
    // 77 districts × all their palikas × every ward
    const wards = JSON.parse(readFileSync(join(out, "report.json"), "utf8")).sitemaps.filter((s: { file: string }) => s.file.startsWith("sitemap-x-nepal-wards-"));
    expect(wards.reduce((n: number, s: { urls: number }) => n + s.urls, 0)).toBeGreaterThan(6_500);
  });

  it("answers an old-address search: Bajhang Chainpur ward 8 → Jayaprithvi ward 11", async () => {
    const vdc = (await exploreResponse(req("/nepal/bajhang/vdc/chainpur"), env))!;
    expect(vdc.status).toBe(200);
    const html = await vdc.text();
    expect(html).toContain("Chainpur VDC ward 8 (Bajhang) is now ward 11 of Jayaprithvi Municipality.");
    expect(html).toContain('href="/nepal/bajhang/jayaprithvi/ward-11"');
    const ward = await (await exploreResponse(req("/nepal/bajhang/jayaprithvi/ward-11"), env))!.text();
    expect(ward).toContain("Chainpur VDC wards 4–9");
    expect(ward).toContain("जयपृथ्वी नगरपालिका वडा नं. ११, बझाङ");
    expect(ward).toContain('"@type":"FAQPage"');
  });

  it("serves an indexable district page with canonical, robots, schema, palikas and sunrise table", async () => {
    const res = (await exploreResponse(req("/nepal/bajhang"), env))!;
    expect(res.status).toBe(200);
    expect(res.headers.get("x-robots-tag")).toBe("index, follow");
    const html = await res.text();
    expect(html).toContain('<link rel="canonical" href="https://aafnaipatro.com/nepal/bajhang">');
    expect(html).toContain('content="index, follow, max-image-preview:large"');
    expect(html).toContain("बझाङ जिल्ला");
    expect(html).toContain('"@type":"BreadcrumbList"');
    expect(html).toContain('href="/nepal/bajhang/jayaprithvi"');
    expect(html).toContain('href="/nepal"'); // breadcrumb to the existing growth page
    expect(html).toMatch(/Sunrise and sunset in .*2083 BS/);
    expect(html).toContain('href="/date/2026-04-14"');
  });

  it("redirects district names at the root, misspellings, ward variants and the old /place URLs", async () => {
    const cases: [string, string][] = [
      ["/dolakha", "/nepal/dolakha"],
      ["/rammechap", "/nepal/ramechhap"],
      ["/Ramechhap/", "/nepal/ramechhap"],
      ["/bhajang", "/nepal/bajhang"],
      ["/nepal/bhajhang", "/nepal/bajhang"],
      ["/nepal/bhajhang/jayaprithvi/ward-08", "/nepal/bajhang/jayaprithvi/ward-8"],
      ["/nepal/bajhang/jayaprithvi-municipality/ward-11", "/nepal/bajhang/jayaprithvi/ward-11"],
      ["/nepal/koshi", "/nepal/koshi-province"],
      ["/place", "/nepal"],
      ["/place/koshi", "/nepal/koshi-province"],
      ["/place/koshi/bhojpur", "/nepal/bhojpur"],
      ["/place/koshi/bhojpur/bhojpur-municipality", "/nepal/bhojpur/bhojpur"],
      ["/place/koshi/pachthar/phidim-municipality", "/nepal/panchthar/phidim"],
    ];
    for (const [from, to] of cases) {
      const res = (await exploreResponse(req(from), env))!;
      expect(res?.status, from).toBe(301);
      expect(res.headers.get("location"), from).toBe(SITE + to);
    }
    // Every redirect target of the old /place pages exists.
    for (const [, to] of cases.filter(([from]) => from.startsWith("/place/") && from.split("/").length > 3)) {
      expect(existsSync(join(out, "pages", to + ".json")), to).toBe(true);
    }
  });

  it("normalises case and trailing slash with a 301", async () => {
    const res = (await exploreResponse(req("/Nepal/Bajhang/"), env))!;
    expect(res.status).toBe(301);
    expect(res.headers.get("location")).toBe(SITE + "/nepal/bajhang");
  });

  it("answers HEAD, 304 and 405 correctly", async () => {
    const head = (await exploreResponse(req("/nepal/bajhang", { method: "HEAD" }), env))!;
    expect(head.status).toBe(200);
    expect(await head.text()).toBe("");
    const etag = head.headers.get("etag")!;
    expect(etag).toMatch(/^"[0-9a-f]{16}"$/);
    const revalidated = (await exploreResponse(req("/nepal/bajhang", { headers: { "if-none-match": etag } }), env))!;
    expect(revalidated.status).toBe(304);
    const post = (await exploreResponse(req("/nepal/bajhang", { method: "POST" }), env))!;
    expect(post.status).toBe(405);
  });

  it("returns noindex 404 for missing or malformed pages without touching storage for bad slugs", async () => {
    for (const path of ["/nepal/bajhang/nowhere", "/nepal/bajhang/x_y", "/nepal/bajhang/" + "a".repeat(400)]) {
      const res = (await exploreResponse(req(path), env))!;
      expect(res.status, path).toBe(404);
      expect(res.headers.get("x-robots-tag")).toContain("noindex");
    }
  });

  it("returns 503 (not 404) when storage is not bound, so crawlers retry", async () => {
    const res = (await exploreResponse(req("/nepal/bajhang"), {}))!;
    expect(res.status).toBe(503);
    expect(res.headers.get("retry-after")).toBe("600");
  });

  it("streams prebuilt sitemaps, one file set per page type, listing only indexable explore URLs", async () => {
    const index = (await exploreResponse(req("/sitemap-explore.xml"), env))!;
    expect(index.status).toBe(200);
    expect(index.headers.get("content-type")).toContain("application/xml");
    const indexXml = await index.text();
    for (const group of ["districts", "palikas", "wards", "vdc", "villages"]) expect(indexXml).toContain(`<loc>https://aafnaipatro.com/sitemap-x-nepal-${group}-0.xml</loc>`);
    const shard = (await exploreResponse(req("/sitemap-x-nepal-wards-0.xml"), env))!;
    const urls = [...(await shard.text()).matchAll(/<loc>([^<]+)<\/loc>/g)].map((m) => m[1]);
    expect(urls.length).toBeGreaterThan(6_500);
    expect(urls.every((u) => /^https:\/\/aafnaipatro\.com\/nepal\/[a-z0-9-]+\/[a-z0-9-]+\/ward-\d+$/.test(u))).toBe(true);
    const districts = await (await exploreResponse(req("/sitemap-x-nepal-districts-0.xml"), env))!.text();
    expect(districts).not.toContain("<loc>https://aafnaipatro.com/nepal</loc>"); // /nepal belongs to the growth page
    expect((await exploreResponse(req("/sitemap-x-unknown-0.xml"), env))!.status).toBe(404);
    expect((await exploreResponse(req("/sitemap-x-nepal-wards-99.xml"), env))!.status).toBe(404);
  });

  it("stores objects only under its own prefix", () => {
    expect(pageKey("/nepal/bajhang")).toBe("explore/v1/pages/nepal/bajhang.json");
    expect(sitemapKey("sitemap-explore.xml")).toBe("explore/v1/sitemaps/sitemap-explore.xml");
  });
});
