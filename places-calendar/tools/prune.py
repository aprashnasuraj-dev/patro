#!/usr/bin/env python3
"""
Demand-based pruning: keep only pages people actually find.

Feed it a Google Search Console "Pages" export (Performance > Pages > Export
CSV, last 3 months). It writes:

  data/noindex.txt      pages built more than --min-age days ago that got
                        fewer than --min-impressions impressions -> noindex
  data/index_allow.txt  OpenStreetMap-imported pages that earned impressions
                        while noindexed (via internal links / Discover) ->
                        promote to indexable

Then rebuild. Pruned pages stay live for visitors and keep passing link
value (noindex, follow); they simply stop competing for crawl budget.

    python tools/prune.py search-console-pages.csv --min-impressions 1 --min-age 90
"""
from __future__ import annotations

import argparse
import csv
import sys
from datetime import date, timedelta
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parent.parent


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("csv", type=Path, help="Search Console Pages export")
    ap.add_argument("--build", type=Path, default=ROOT / "build", help="Built site, to list every page")
    ap.add_argument("--min-impressions", type=int, default=1)
    ap.add_argument("--min-age", type=int, default=90, help="Only prune pages older than this many days")
    a = ap.parse_args()

    impressions: dict[str, int] = {}
    with a.csv.open(encoding="utf-8-sig") as f:
        rdr = csv.DictReader(f)
        page_col = next(c for c in rdr.fieldnames if c.lower().startswith(("top pages", "page")))
        imp_col = next(c for c in rdr.fieldnames if c.lower().startswith("impressions"))
        for row in rdr:
            path = urlparse(row[page_col]).path
            if path.startswith("/ne/"):
                path = path[3:]            # judge each en/ne pair together
            impressions[path] = impressions.get(path, 0) + int(row[imp_col].replace(",", "") or 0)

    cutoff = date.today() - timedelta(days=a.min_age)
    pruned, promoted = [], []
    for html in a.build.rglob("index.html"):
        rel = "/" + str(html.parent.relative_to(a.build)).replace("\\", "/") + "/"
        if rel.startswith("/ne/"):
            continue
        age_ok = date.fromtimestamp(html.stat().st_mtime) <= cutoff or a.min_age == 0
        imp = impressions.get(rel, 0)
        text = html.read_text(encoding="utf-8", errors="ignore")
        is_noindex = 'content="noindex' in text
        if not is_noindex and imp < a.min_impressions and age_ok:
            pruned.append(rel)
        elif is_noindex and imp >= a.min_impressions:
            promoted.append(rel)

    (ROOT / "data" / "noindex.txt").write_text(
        "# Generated by tools/prune.py — pages with too little demand\n" + "\n".join(sorted(pruned)) + "\n", encoding="utf-8")
    (ROOT / "data" / "index_allow.txt").write_text(
        "# Generated by tools/prune.py — imported pages that earned impressions\n" + "\n".join(sorted(promoted)) + "\n", encoding="utf-8")
    print(f"noindex: {len(pruned)} pages, promoted: {len(promoted)} pages. Rebuild to apply.")


if __name__ == "__main__":
    sys.exit(main())
